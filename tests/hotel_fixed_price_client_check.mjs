import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const code=fs.readFileSync('app/webapp/js/hotel-pricing.js','utf8').replace(/^import .*;$/gm,'').replaceAll('export function','function');
const ctx=vm.createContext({document:{addEventListener(){}},esc:x=>String(x??'').replaceAll('<','&lt;'),Number,Math});
vm.runInContext(code,ctx);
const booking={id:1,hotelId:1,price:'400.00',pricing:{kind:'UNIT',price:'400.00',tariffId:1},paidAmount:'1000.00',declaredDeposit:'1000.00',salesAmount:'0'};
const tariffs=[{id:2,hotelId:1,kind:'UNIT',price:'500.00'}, {id:3,hotelId:1,kind:'PACKAGE',price:'3200.00',name:'Ten',photoCount:10}, {id:4,hotelId:2,kind:'PACKAGE',price:'100.00',name:'Other'}];
ctx.b=booking;ctx.tariffs=tariffs;
const options=vm.runInContext('tariffOptions(b,tariffs)',ctx);
assert.ok(options.includes('400.00'));
assert.ok(!options.includes('500.00'),'another unit price must not be offered for this booking');
assert.ok(!options.includes('Other'),'packages from another hotel must not be offered');
const form={elements:{tariffId:{value:'1'},sold:{value:'10'}},querySelector:()=>({textContent:''})};
ctx.form=form;
let quote=vm.runInContext('updatePricePreview(form,b,tariffs)',ctx);
assert.equal(quote.amount,4000);assert.equal(quote.due,3000);
booking.paidAmount='1500';quote=vm.runInContext('updatePricePreview(form,b,tariffs)',ctx);assert.equal(quote.due,2500);
booking.paidAmount='0';quote=vm.runInContext('updatePricePreview(form,b,tariffs)',ctx);assert.equal(quote.due,4000,'declared deposit is not confirmed money');
booking.paidAmount='1000';form.elements.tariffId.value='3';quote=vm.runInContext('updatePricePreview(form,b,tariffs)',ctx);assert.equal(quote.amount,3200);assert.equal(quote.due,2200);
form.elements.tariffId.value='2';assert.equal(vm.runInContext('updatePricePreview(form,b,tariffs)',ctx),null,'tampered alternate unit rate is not previewed');
booking.salesAmount='4000';booking.paidAmount='4500';form.elements.tariffId.value='1';form.elements.sold.value='2';quote=vm.runInContext('updatePricePreview(form,b,tariffs)',ctx);assert.equal(quote.amount,800);assert.equal(quote.due,300,'prior payments offset the whole booking once');
console.log('PASS: fixed booking price, package isolation, variable deposits and additional sale balance');
